/**
 * Build the global search index.
 *
 * The map has thousands of features across two dozen layers, but only the
 * features that carry a real identity (a name, street, ref, code, operator,
 * ...) are worth searching for. Anonymous "Footway"/"Stream" features are
 * excluded: they would swamp the results with identical rows and there is
 * nothing to match on anyway. Browse within a layer still reaches those.
 *
 * Each entry is [layerIndex, label, lon, lat]; the layer table maps the index
 * back to a layer id and label. Coordinates are the feature centre, the same
 * point the Browse panel flies to.
 *
 * Reads the shipped public/data files only - no network.
 *
 *   node --experimental-strip-types scripts/build-search-index.mjs
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { writeJSON } from "./lib/fetch.mjs";
import { LAYERS } from "../src/lib/layers.ts";
import { featureCentre, browseLabel } from "../src/lib/feature-index.ts";
import { hasIdentity } from "../src/lib/feature-label.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "public", "data");
const OUT = path.join(DATA, "search-index.json");

/** Longest label stored, so one malformed value cannot bloat the file. */
const MAX_LABEL = 96;

function build() {
  const geo = LAYERS.filter((l) => l.kind === "geojson" && l.file && fs.existsSync(path.join(DATA, l.file)));

  const layerTable = geo.map((l) => ({ id: l.id, label: l.label }));
  const entries = [];
  let skipped = 0;

  geo.forEach((layer, li) => {
    let fc;
    try {
      fc = JSON.parse(fs.readFileSync(path.join(DATA, layer.file), "utf8"));
    } catch {
      return;
    }
    for (const f of fc.features ?? []) {
      const props = f.properties ?? null;
      if (!hasIdentity(props)) {
        skipped++;
        continue;
      }
      const centre = featureCentre(f.geometry);
      if (!centre) continue;
      const label = browseLabel(props).replace(/\s+/g, " ").trim().slice(0, MAX_LABEL);
      if (!label || label === "(unnamed)") continue;
      entries.push([li, label, Number(centre[0].toFixed(5)), Number(centre[1].toFixed(5))]);
    }
  });

  const index = {
    // Deliberately no timestamp: this file is rebuilt on every `npm run build`,
    // and a volatile field would leave every build with a dirty working tree.
    note: "Generated by scripts/build-search-index.mjs. Entries are [layerIndex, label, lon, lat].",
    layers: layerTable,
    entries,
  };

  const bytes = writeJSON(OUT, index);
  console.log(
    `search-index.json: ${entries.length} searchable features across ${layerTable.length} layers, ${skipped} anonymous skipped (${(bytes / 1024).toFixed(1)} KB)`,
  );
}

build();
