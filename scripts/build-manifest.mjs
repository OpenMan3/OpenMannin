/**
 * Build the data manifest.
 *
 * The layer registry is hand-written, so "does this layer actually have data?"
 * and "how many features does it have?" cannot be answered from it without
 * either going stale or probing every file from the browser at page load. The
 * browser probe cost eleven 404s on first paint.
 *
 * This scans public/data once at ingest time and records what is really there.
 * The app then needs a single small request to know the truth.
 *
 * Run with:  node --experimental-strip-types scripts/build-manifest.mjs
 */

import { writeJSON } from "./lib/fetch.mjs";

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { LAYERS } from "../src/lib/layers.ts";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA = path.join(ROOT, "public", "data");
const OUT = path.join(DATA, "manifest.json");

const layers = {};
let ok = 0;
const absent = [];

for (const l of LAYERS) {
  if (l.kind !== "geojson" || !l.file) continue;
  const p = path.join(DATA, l.file);

  if (!fs.existsSync(p)) {
    absent.push(l.id);
    layers[l.id] = { file: l.file, present: false };
    continue;
  }

  const stat = fs.statSync(p);
  let features;
  try {
    const g = JSON.parse(fs.readFileSync(p, "utf8"));
    features = Array.isArray(g.features) ? g.features.length : 0;
  } catch (e) {
    layers[l.id] = { file: l.file, present: false, error: `invalid JSON: ${e.message}` };
    absent.push(l.id);
    continue;
  }

  layers[l.id] = {
    file: l.file,
    present: features > 0,
    features,
    bytes: stat.size,
  };
  if (features > 0) ok++;
}

const manifest = {
  note: "Generated by scripts/build-manifest.mjs. Do not edit by hand.",
  generated: new Date().toISOString().slice(0, 10),
  present: ok,
  absent,
  layers,
};

writeJSON(OUT, manifest, { pretty: true, trailingNewline: true });

const kb = (fs.statSync(OUT).size / 1024).toFixed(1);
console.log(`manifest.json: ${ok} layers with data, ${absent.length} without (${kb} kB)`);
if (absent.length) console.log(`  no data: ${absent.join(", ")}`);